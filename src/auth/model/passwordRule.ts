// 서버 가입 규칙(ipgo-server PR #35)과 같다: 8~10자, 영문 대문자·소문자·숫자·특수기호 각 1개 이상,
// 공백 없는 ASCII(`!`부터 `~`까지)만. 한글·이모지·공백은 안 된다. 화면 검사와 가짜 서버가 함께 쓴다.
export const PASSWORD_RULE =
  /^(?=.*[A-Z])(?=.*[a-z])(?=.*\d)(?=.*[!-/:-@[-`{-~])[!-~]{8,10}$/

export const PASSWORD_RULE_MESSAGE =
  '8~10자로 영문 대문자·소문자·숫자·특수문자를 모두 넣어 주세요.'

export const PASSWORD_RULE_HINT =
  '영문 대문자·소문자, 숫자, 특수문자를 모두 넣어 8~10자로 정해 주세요. 공백·한글은 쓸 수 없어요.'
